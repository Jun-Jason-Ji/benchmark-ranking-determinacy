"""Implementation-build drift, measured on a properly paired episode scope.

Why this script exists. FINDING_platform_drift.md records the octo-base nominal cell as
0.297 (pre-fix) vs 0.375 (A'), a drift of 0.078. Recomputing it later gave 0.352 vs 0.375 = 0.023,
which looked like the data had changed underneath the finding. It had not. The pre-fix directory
holds 96 episodes (ids 0-95) while A' holds 64 (ids 0-63), and with 64 configurations ids 64-95 wrap
onto configs 0-31. So a naive per-configuration mean over the pre-fix directory averages two
observations for half the configurations and one for the other half, against one apiece on the A'
side -- an unpaired comparison over different effective scopes.

Build drift is defined as "same seeds, different build" (Sect. 5.5), which is a paired quantity. It
therefore has to be computed on the episode ids the two builds have in common, one observation per
configuration on each side. That is what this script does, and it reports the naive figure alongside
so the difference between the two is visible rather than silently resolved.

Usage: python scripts/analyze_platform_drift_paired.py
"""
import argparse
import io
import json
import sys
from pathlib import Path

try:
    sys.stdout.reconfigure(encoding="utf-8")
except Exception:
    pass
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
from task_configs import config_id, n_configs  # noqa: E402

EGG = "PutEggplantInBasketScene-v1"
NC = n_configs(EGG)
PRE = "results/controller_sweep_gpu"
POST = "results/controller_sweep_gpu_replayA"
POLICIES = ("octo-small", "octo-base")
CONDS = ("nominal", "force_x0.5")


def episodes(root, policy, cond):
    """episode_id -> outcome, first occurrence wins."""
    f = ROOT / root / policy / EGG / f"{cond}.jsonl"
    out = {}
    if f.exists():
        for line in io.open(f, encoding="utf-8"):
            if line.strip():
                r = json.loads(line)
                out.setdefault(r["episode_id"], int(bool(r["success"])))
    return out


def rate_by_config(eps, ids=None):
    """Mean over configurations of the mean outcome at that configuration."""
    acc = {}
    for e, s in eps.items():
        if ids is not None and e not in ids:
            continue
        acc.setdefault(config_id(EGG, e), []).append(s)
    if not acc:
        return float("nan"), 0, 0
    per_cfg = [float(np.mean(v)) for v in acc.values()]
    obs = sum(len(v) for v in acc.values())
    return float(np.mean(per_cfg)), len(acc), obs


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="results/controller_sweep_gpu_replayA/analysis_drift_paired.md")
    args = ap.parse_args()

    L = ["# Generated: implementation-build drift on a paired episode scope", "",
         "Generated by `scripts/analyze_platform_drift_paired.py`.", "",
         f"Build drift is a paired quantity: same seeds, different build. With {NC} configurations,",
         "episode ids beyond the grid wrap onto it, so the two builds must be compared on the episode",
         "ids they share, one observation per configuration on each side. The naive column shows what",
         "an unpaired per-configuration mean over each directory's full contents gives instead.", "",
         "| policy | condition | pre eps | post eps | shared | naive drift | **paired drift** |",
         "|---|---|---:|---:|---:|---:|---:|"]
    paired, naive = [], []
    for p in POLICIES:
        for c in CONDS:
            a, b = episodes(PRE, p, c), episodes(POST, p, c)
            if not a or not b:
                continue
            shared = set(a) & set(b)
            ra_n, _, _ = rate_by_config(a)
            rb_n, _, _ = rate_by_config(b)
            ra_p, ncfg, _ = rate_by_config(a, shared)
            rb_p, _, _ = rate_by_config(b, shared)
            dn, dp = abs(ra_n - rb_n), abs(ra_p - rb_p)
            naive.append(dn)
            paired.append(dp)
            L.append(f"| {p} | `{c}` | {len(a)} | {len(b)} | {len(shared)} | {dn:+.3f} | "
                     f"**{dp:+.3f}** |")
    L += ["",
          f"Maximum paired drift: **{max(paired):.3f}**. Mean **{np.mean(paired):.3f}**.",
          f"Maximum naive drift: {max(naive):.3f} (mean {np.mean(naive):.3f}).", ""]

    # The specific cell the original finding quotes.
    a, b = episodes(PRE, "octo-base", "nominal"), episodes(POST, "octo-base", "nominal")
    shared = set(a) & set(b)
    ra_p, _, _ = rate_by_config(a, shared)
    rb_p, _, _ = rate_by_config(b, shared)
    ra_n, _, _ = rate_by_config(a)
    L += ["## The cell FINDING_platform_drift.md quotes", "",
          f"- recorded: pre 0.297 vs post 0.375, drift 0.078",
          f"- paired on the {len(shared)} shared episode ids: pre {ra_p:.3f} vs post {rb_p:.3f}, "
          f"drift {abs(ra_p - rb_p):.3f}",
          f"- naive over the full pre-fix directory ({len(a)} episodes): {ra_n:.3f}",
          "",
          "If the paired figure reproduces 0.297/0.078, the recorded number was right and the later",
          "recomputation was the unpaired one. The paper should then state the paired value and say",
          "explicitly that it is paired on the shared ids.", ""]

    out = ROOT / args.out
    out.write_text("\n".join(L), encoding="utf-8")
    print("\n".join(L))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
