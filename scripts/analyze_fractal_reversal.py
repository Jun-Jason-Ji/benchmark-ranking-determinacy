"""The real-vs-sim reversal pair on fractal: does the compatible-set verdict abstain where the simulator
gets the ordering wrong?

`simpler_env/utils/metrics.py` publishes both real-robot and simulated success rates for the same policies.
On pick-coke-can, rt-1-converged vs rt-1-15pct is the only pair whose orderings disagree *and* whose
checkpoints are both public:

    real  0.853 vs 0.920  =  -0.067   (15pct better)
    sim   0.857 vs 0.710  =  +0.147   (converged better)

`queue_fractal_reversal.py` ran both checkpoints over the complete 300-configuration census under nominal
plus the two calibration-invisible conditions that moved verdicts on bridge (torque limit, object friction).
This script reduces those 1800 episodes to the verdict tables.

Two set definitions are reported, because they answer different questions:
  ctrl     - the dynamics compatible set as scoped (nominal, force_x0.5, fric_x0.4)
  ctrl+vis - the same, sliced by `urdf_version`, the robot texture variant the benchmark silently averages
             over (fractal_validation/FINDING_urdf_variance.md). It is invisible to replay calibration for
             the same reason the torque limit is: it carries no physics at all.

The ctrl+vis row must be read with its power caveat, which the output states: at 75 configurations per cell
the intervals are wide enough to cover zero while every point margin stays positive, so an abstention there
is our own sample size, not parameter-induced ambiguity. See scripts/analyze_benchmark_value.py for the same
distinction drawn on bridge.

Writes the generated table only. The interpretation belongs in a hand-written FINDING_fractal_reversal.md
(convention adopted 2026-09-19 after a refresh queue overwrote a hand-written FINDING).

Usage: python scripts/analyze_fractal_reversal.py
"""
import argparse
import json
import sys
from pathlib import Path

try:
    sys.stdout.reconfigure(encoding="utf-8")
except Exception:
    pass
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results/fractal_reversal"
ENV = "GraspSingleOpenedCokeCanInScene-v0"
POLICIES = ("rt-1-converged", "rt-1-15pct")
CONDS = ("nominal", "force_x0.5", "fric_x0.4")
# scripts/controller_sweep_ms2.py: urdf = urdf_versions[(ep % 300) // (n_xy * ncan)], n_xy * ncan = 75
URDF = ("None (default)", "recolor_tabletop_1", "recolor_tabletop_2", "recolor_cabinet_1")
URDF_BLOCK = 75
# metrics.py REAL_PERF / SIMPLER_PERF, google_robot_pick_coke_can
PUBLISHED = {"real": {"rt-1-converged": 0.853, "rt-1-15pct": 0.920},
             "sim": {"rt-1-converged": 0.857, "rt-1-15pct": 0.710}}


def load(policy, cond):
    """episode_id -> success, for one cell."""
    out = {}
    path = RES / policy / ENV / f"{cond}.jsonl"
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.strip():
            r = json.loads(line)
            out[r["episode_id"]] = float(r["success"])
    return out


def boot(diff, n_boot, seed=0):
    """Paired bootstrap CI over episodes. Configurations are enumerated, so the pairing is exact:
    equal episode_id means the identical initial state for both policies (scripts/task_configs.py)."""
    rng = np.random.default_rng(seed)
    means = diff[rng.integers(0, len(diff), (n_boot, len(diff)))].mean(axis=1)
    return float(np.percentile(means, 2.5)), float(np.percentile(means, 97.5))


def cell(cond, urdf_idx=None, n_boot=20000):
    a, b = load(POLICIES[0], cond), load(POLICIES[1], cond)
    ids = sorted(set(a) & set(b))
    if urdf_idx is not None:
        ids = [i for i in ids if (i % 300) // URDF_BLOCK == urdf_idx]
    d = np.array([a[i] - b[i] for i in ids])
    lo, hi = boot(d, n_boot)
    return {"n": len(ids), "a": float(np.mean([a[i] for i in ids])),
            "b": float(np.mean([b[i] for i in ids])), "margin": float(d.mean()), "lo": lo, "hi": hi}


def verdict(lo, hi):
    if lo > 0:
        return f"**declare** {POLICIES[0]} > {POLICIES[1]}"
    if hi < 0:
        return f"**declare** {POLICIES[1]} > {POLICIES[0]}"
    return "abstain"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(RES / "analysis_fractal_reversal.md"))
    ap.add_argument("--n-boot", type=int, default=20000)
    args = ap.parse_args()

    ctrl = {c: cell(c, n_boot=args.n_boot) for c in CONDS}
    vis = {(u, c): cell(c, u, n_boot=args.n_boot) for u in range(len(URDF)) for c in CONDS}

    real_margin = PUBLISHED["real"][POLICIES[0]] - PUBLISHED["real"][POLICIES[1]]
    sim_margin = PUBLISHED["sim"][POLICIES[0]] - PUBLISHED["sim"][POLICIES[1]]

    L = ["# Generated: the fractal real-vs-sim reversal pair",
         "",
         "Generated by `scripts/analyze_fractal_reversal.py`. Tables only — interpretation lives in",
         "`FINDING_fractal_reversal.md`.",
         "",
         f"Pair: **{POLICIES[0]}** vs **{POLICIES[1]}**, `{ENV}`, complete 300-configuration census per",
         "condition (1800 episodes total). Margin is always the first policy minus the second, paired by",
         "`episode_id` (equal id = identical initial state). Intervals are paired bootstrap 95%,",
         f"{args.n_boot} resamples.",
         "",
         "## Reference values (`simpler_env/utils/metrics.py`)",
         "",
         "| source | rt-1-converged | rt-1-15pct | margin |",
         "|---|---:|---:|---:|",
         f"| published real robot | {PUBLISHED['real'][POLICIES[0]]:.3f} | "
         f"{PUBLISHED['real'][POLICIES[1]]:.3f} | {real_margin:+.3f} |",
         f"| published simulation | {PUBLISHED['sim'][POLICIES[0]]:.3f} | "
         f"{PUBLISHED['sim'][POLICIES[1]]:.3f} | {sim_margin:+.3f} |",
         f"| our nominal census | {ctrl['nominal']['a']:.3f} | {ctrl['nominal']['b']:.3f} | "
         f"{ctrl['nominal']['margin']:+.3f} |",
         "",
         f"Reproduction of the published simulated rates: {ctrl['nominal']['a'] - PUBLISHED['sim'][POLICIES[0]]:+.3f} "
         f"and {ctrl['nominal']['b'] - PUBLISHED['sim'][POLICIES[1]]:+.3f}.",
         "",
         "## Per condition (dynamics compatible set)",
         "",
         "| condition | rt-1-converged | rt-1-15pct | margin | 95% CI | n pairs |",
         "|---|---:|---:|---:|---|---:|"]
    for c in CONDS:
        r = ctrl[c]
        L.append(f"| `{c}` | {r['a']:.3f} | {r['b']:.3f} | {r['margin']:+.3f} | "
                 f"[{r['lo']:+.3f}, {r['hi']:+.3f}] | {r['n']} |")

    L += ["",
          "## Per condition x URDF texture variant",
          "",
          "| urdf_version | condition | rt-1-converged | rt-1-15pct | margin | 95% CI | n pairs |",
          "|---|---|---:|---:|---:|---|---:|"]
    for u, name in enumerate(URDF):
        for c in CONDS:
            r = vis[(u, c)]
            L.append(f"| `{name}` | `{c}` | {r['a']:.3f} | {r['b']:.3f} | {r['margin']:+.3f} | "
                     f"[{r['lo']:+.3f}, {r['hi']:+.3f}] | {r['n']} |")

    pt = ctrl["nominal"]
    l_ctrl = min(ctrl[c]["lo"] for c in CONDS)
    u_ctrl = max(ctrl[c]["hi"] for c in CONDS)
    l_vis = min(v["lo"] for v in vis.values())
    u_vis = max(v["hi"] for v in vis.values())
    min_point_vis = min(v["margin"] for v in vis.values())
    n_neg_point = sum(1 for v in vis.values() if v["margin"] < 0)
    n_neg_decl = sum(1 for v in vis.values() if v["hi"] < 0)

    L += ["",
          "## Verdicts",
          "",
          "| criterion | set | bound | verdict |",
          "|---|---|---|---|",
          f"| point calibration | nominal only | [{pt['lo']:+.3f}, {pt['hi']:+.3f}] | {verdict(pt['lo'], pt['hi'])} |",
          f"| union bound | ctrl ({len(CONDS)} cells) | L = {l_ctrl:+.3f}, U = {u_ctrl:+.3f} | "
          f"{verdict(l_ctrl, u_ctrl)} |",
          f"| union bound | ctrl+vis ({len(vis)} cells) | L = {l_vis:+.3f}, U = {u_vis:+.3f} | "
          f"{verdict(l_vis, u_vis)} |",
          f"| published real robot | — | {real_margin:+.3f} | {POLICIES[1]} > {POLICIES[0]} |",
          "",
          "## Power caveat on the ctrl+vis row",
          "",
          f"Of the {len(vis)} variant x condition cells, {n_neg_point} have a negative point margin and",
          f"{n_neg_decl} place {POLICIES[1]} above {POLICIES[0]} with interval support. The smallest point",
          f"margin is {min_point_vis:+.3f}. The ctrl+vis bound therefore reaches L = {l_vis:+.3f} only through",
          f"interval width at {vis[(0, 'nominal')]['n']} configurations per cell: as the budget grows,",
          f"L tends to {min_point_vis:+.3f} and the abstention disappears. Read it as insufficient power, not",
          "as parameter-induced ambiguity — the distinction T2-A was run to draw on bridge",
          "(`controller_sweep_gpu_rep3/FINDING_t2a_seeds.md`).",
          ""]

    out = Path(args.out)
    out.write_text("\n".join(L), encoding="utf-8")
    print(f"wrote {out}")
    print(f"  point (nominal)  : [{pt['lo']:+.3f}, {pt['hi']:+.3f}]  {verdict(pt['lo'], pt['hi'])}")
    print(f"  union ctrl       : L={l_ctrl:+.3f} U={u_ctrl:+.3f}  {verdict(l_ctrl, u_ctrl)}")
    print(f"  union ctrl+vis   : L={l_vis:+.3f} U={u_vis:+.3f}  {verdict(l_vis, u_vis)}")
    print(f"  real robot       : {real_margin:+.3f}  {POLICIES[1]} > {POLICIES[0]}")


if __name__ == "__main__":
    main()
