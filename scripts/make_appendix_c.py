"""Emit Appendix C: the complete condition table with per-cell configuration and run counts.

Figure 4's caption points here for the per-condition episode counts, and the intervals in Table 6
cannot be interpreted without knowing how many configurations and how many independent runs each
cell rests on. Generated from the records so it cannot drift.

Usage: python scripts/make_appendix_c.py   (prints a LaTeX tabular to stdout and writes a fragment)
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
import make_core_table as mct  # noqa: E402
from task_configs import n_configs  # noqa: E402

TASKS = [("carrot", "PutCarrotOnPlateInScene-v1"), ("spoon", "PutSpoonOnTableClothInScene-v1"),
         ("eggplant", "PutEggplantInBasketScene-v1")]
CONDS = ["nominal"] + list(mct.INVISIBLE)
A, B = "octo-small", "octo-base"


def runs_per_config(sets, policy, env, cond):
    """How many observations each configuration actually has, as {count: how many configs}.

    The old column reported the number of seed-set DIRECTORIES, which is not the per-configuration
    run count and overstated it for some cells and understated it for others. Seed set B holds 96
    episodes on a 64-configuration grid, so ids 64-95 wrap onto configs 0-31 and give those an extra
    observation; conversely some conditions were not run in every set. On the eggplant census the
    truth is 48 configs with 5 runs and 16 with 4 for three conditions, and 32 with 6 and 32 with 5
    for two others. Eq. (eq:var) uses the per-configuration S_c, so the estimator was always right;
    it is the table that has to say so.
    """
    from collections import Counter
    import json
    from task_configs import config_id
    per = {}
    for root in sets.values():
        f = ROOT / root / policy / env / f"{cond}.jsonl"
        if not f.exists():
            continue
        seen = set()
        for line in f.read_text(encoding="utf-8").splitlines():
            if not line.strip():
                continue
            r = json.loads(line)
            e = r["episode_id"]
            if e in seen:
                continue
            seen.add(e)
            per.setdefault(config_id(env, e), 0)
            per[config_id(env, e)] += 1
    return Counter(per.values())


def fmt_runs(dist):
    """'5x48, 4x16' -- runs per configuration and how many configurations have that many."""
    if not dist:
        return "--"
    return ", ".join(f"{k}$\\times${v}" for k, v in sorted(dist.items(), reverse=True))


def main():
    mct.SETS_MS3 = dict(mct.SEED_SETS_OCTO)
    sets = mct.SETS_MS3
    rows = []
    for name, env in TASKS:
        total = n_configs(env)
        for c in CONDS:
            r = mct.delta(sets, A, B, env, c)
            if not r:
                rows.append((name, c, total, None, None, None))
                continue
            rows.append((name, c, total, r["n"], r["runs"], r["delta"]))

    L = ["% Appendix C, generated by scripts/make_appendix_c.py -- do not hand-edit.",
         r"\begin{tabular}{@{}llrrlll@{}}", r"\toprule",
         r"Task & Condition & Configs & Covered & Sets & Runs per config, S & Runs per config, B \\",
         r"\midrule"]
    last = None
    for name, c, total, n, runs, d in rows:
        task_cell = name if name != last else ""
        last = name
        cond_tex = "\\texttt{" + c.replace("_", chr(92) + "_") + "}"
        if n is None:
            L.append(f"{task_cell} & {cond_tex} & {total} & \\multicolumn{{4}}{{c}}{{not run}} \\\\")
        else:
            env = dict(TASKS)[name]
            da = fmt_runs(runs_per_config(sets, A, env, c))
            db = fmt_runs(runs_per_config(sets, B, env, c))
            L.append(f"{task_cell} & {cond_tex} & {total} & {n} & {runs[0]}/{runs[1]} & "
                     f"{da} & {db} \\\\")
        if c == CONDS[-1] and name != TASKS[-1][0]:
            L.append(r"\midrule")
    L += [r"\bottomrule", r"\end{tabular}"]

    out = ROOT / "results/appendix_c_table.tex"
    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))
    print(f"\n% wrote {out}", file=sys.stderr)


if __name__ == "__main__":
    main()
