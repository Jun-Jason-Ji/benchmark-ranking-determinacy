"""One policy pair, end to end: calibration sensitivity, policy difference, verdict.

Reviewers of earlier drafts made the same complaint twice in different words: the paper reports the
largest parameter effect on one policy pair, the verdict change on a second, and a third arm's
published real means, and a reader can be left with the impression that those form one closed loop.
They do not. This script builds the loop that does exist, on a single pair, with every scope
parameter printed beside it.

The pair is octo-small vs octo-base on the ManiSkill3 eggplant census: five seed sets, all 64
configurations enumerated, one inference-stack build. It is the pair the paper follows through
Sect. 4.4 (which directions the replay loss can see), Sect. 7.2 (the per-condition differences and
the two verdicts) and Sect. 7.7 (what happens at the calibration-preferred operating point), so it
is the one for which the chain can be closed from the records rather than assembled across pairs.

Three columns and they must not be read as commensurable. The replay-loss column is the calibration
protocol's sensitivity to the condition, in the composite units of Eq. (eq:loss); the Delta column is
the policy difference in probability points with its census interval; the verdict column is what the
decision rule returns. The first says whether the calibration evidence can distinguish the condition
from nominal, the second says how much the policy comparison moves there, and the point of the table
is that the two are unrelated in magnitude: conditions the protocol cannot see at all move Delta by
as much as conditions it identifies.

Usage: python scripts/make_evidence_chain.py [--out results/EVIDENCE_CHAIN.md]
"""
import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
import make_core_table as mct  # noqa: E402

ENV = "PutEggplantInBasketScene-v1"
A, B = "octo-small", "octo-base"

# Calibration sensitivity of each policy-sweep condition, from Sect. 4.2-4.4. "seen" says whether
# the replay protocol can distinguish the condition from nominal at all; the magnitude is the
# largest paired mean loss difference we measured, in composite units.
#   measured-flat : the loss was measured along this direction and is flat to the stated magnitude
#   unobserved    : the parameter never enters a free-space replay trajectory, so there is nothing
#                   to measure -- a coverage gap, not a precision limit
#   identified    : the loss moves, and the protocol prefers a different value
CALIB = {
    "nominal":    ("base point", "0 by construction"),
    "iso_x0.25":  ("measured flat", "$\\le 3.1\\times10^{-6}$"),
    "iso_x4.0":   ("measured flat", "$\\le 3.1\\times10^{-6}$"),
    "force_x0.5": ("measured flat", "$\\le 1.8\\times10^{-8}$"),
    "fric_x0.4":  ("unobserved", "not in a free-space replay"),
    "dens_x0.5":  ("unobserved", "not in a free-space replay"),
}
ORDER = ["nominal", "iso_x0.25", "iso_x4.0", "force_x0.5", "fric_x0.4", "dens_x0.5"]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="results/EVIDENCE_CHAIN.md")
    args = ap.parse_args()

    mct.SETS_MS3 = dict(mct.SEED_SETS_OCTO)
    sets = mct.SETS_MS3
    rows = []
    for c in ORDER:
        r = mct.delta(sets, A, B, ENV, c)
        if r:
            rows.append((c, r))
    if not rows:
        raise SystemExit("no records for this pair")

    nom = dict(rows)["nominal"]
    lo = min(r["lo"] for _, r in rows)
    hi = max(r["hi"] for _, r in rows)
    n_cfg = nom["n"]

    L = [f"# One pair end to end: `{A}` vs `{B}`, {ENV}", "",
         f"Scope, stated once and true of every row: all **{n_cfg} configurations** enumerated "
         f"(configuration sampling error exactly zero), **{len(mct.SEED_SETS_OCTO)} seed sets** "
         f"({', '.join(mct.SEED_SETS_OCTO)}), **one inference-stack build**, run observation unit, "
         "estimator Eq. (eq:var), empirical variance on both sides. Generated by "
         "`scripts/make_evidence_chain.py`.", "",
         "The three quantities are not commensurable and the table exists to show that they are "
         "unrelated in magnitude. Column 2 is what the calibration protocol can see, in the "
         "composite units of Eq. (eq:loss). Column 4 is how far the policy difference moves, in "
         "probability points. A condition the protocol cannot distinguish from nominal at all moves "
         "$\\hat\\Delta$ as much as one it identifies.", "",
         "| condition | calibration sees it? | replay-loss change | $\\hat\\Delta$ | 95% census interval | verdict |",
         "|---|---|---|---:|---|---|"]
    for c, r in rows:
        seen, mag = CALIB[c]
        v = mct.verdict(r["lo"], r["hi"], A, B)
        L.append(f"| `{c}` | {seen} | {mag} | {r['delta']:+.3f} | "
                 f"[{r['lo']:+.3f}, {r['hi']:+.3f}] | {v} |")
    L += [f"| **union over the fibre** | --- | --- | --- | "
          f"**[{lo:+.3f}, {hi:+.3f}]** | **{mct.verdict(lo, hi, A, B)}** |", ""]

    pv = mct.verdict(nom["lo"], nom["hi"], A, B)
    uv = mct.verdict(lo, hi, A, B)
    L += ["## Reading it", "",
          f"- **Point calibration** evaluates the first row only: $\\hat\\Delta = {nom['delta']:+.3f}$, "
          f"[{nom['lo']:+.3f}, {nom['hi']:+.3f}], verdict *{pv}*.",
          f"- **The union bound** takes the minimum lower bound and the maximum upper bound over the "
          f"whole fibre: [{lo:+.3f}, {hi:+.3f}], verdict *{uv}*.",
          f"- The two {'agree' if pv == uv else 'disagree'} on this pair at this budget.", "",
          "- The spread of $\\hat\\Delta$ across the fibre is "
          f"{max(r['delta'] for _, r in rows) - min(r['delta'] for _, r in rows):+.3f}, produced by "
          "conditions whose replay-loss differences from nominal are at most $3.1\\times10^{-6}$ "
          "composite or are not measurable at all. That gap between what calibration resolves and "
          "what the policy comparison responds to is the chain this table closes.", "",
          "## What this table does not do", "",
          "- It does not carry the operating-point result. That needs a second census at the fitted "
          "controller setting and is Table 10 of the paper, on the same pair but at three seed sets "
          "so the two operating points are compared at a matched budget.",
          "- It does not carry the torque-shift magnitude of Sect. 7.3. That effect is on the "
          "cross-family Octo-versus-OpenVLA pairs, where a large-displacement policy saturates "
          "contact torque; on this Octo-versus-Octo pair the same parameter moves $\\hat\\Delta$ by "
          "much less. Quoting the two together would be the splice this table is meant to prevent.",
          "- It does not speak about the real robot. No row here has real-robot ground truth.", ""]

    text = "\n".join(L)
    (ROOT / args.out).write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
