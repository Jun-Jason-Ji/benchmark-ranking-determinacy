"""Per-pair torque-limit shift on the eggplant census at S = 5, with intervals.

Section 7.3's table of cross-family shifts was measured at three seed sets and averages to 0.141.
The paper's standard scope is now S = 5 (the budget T2-A established, and the one Fig. 2 is computed
on), where the mean shift is 0.121. Quoting 0.121 as delta while printing a table that averages to
0.141 would be inconsistent, so this recomputes the table at S = 5.

Delta is the benchmark-value estimator of Sect. 5.4: the configuration grid is fully enumerated, so
configuration sampling error is zero and the interval carries policy noise only, pooled per
configuration across seed sets. OpenVLA decodes deterministically, so its record-identical repeat
runs are merged into one observation (Sect. 5.3).

Usage: python scripts/analyze_torque_shift_s5.py
"""
import argparse
import itertools
import json
import sys
from pathlib import Path

try:
    sys.stdout.reconfigure(encoding="utf-8")
except Exception:
    pass
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
from task_configs import config_id, is_deterministic, n_configs  # noqa: E402

EGG = "PutEggplantInBasketScene-v1"
NC = n_configs(EGG)
OCTO_SETS = {"A'": "results/controller_sweep_gpu_replayA", "B": "results/controller_sweep_gpu_rep",
             "C": "results/controller_sweep_gpu_rep3", "D": "results/controller_sweep_gpu_rep4",
             "E": "results/controller_sweep_gpu_rep5"}
DET_SETS = dict(OCTO_SETS, **{"A'": "results/controller_sweep_gpu"})
OCTO = ["octo-small", "octo-base", "octo-small@hist1", "octo-base@hist1"]
OPENVLA = "openvla-7b-4bit"
CONDS = ("nominal", "force_x0.5")


def per_config_runs(root, policy, cond):
    """{config: [outcomes]} for one seed-set directory, de-duplicating repeated episode ids."""
    f = ROOT / root / policy / EGG / f"{cond}.jsonl"
    acc, seen = {}, set()
    if f.exists():
        for line in f.read_text(encoding="utf-8").splitlines():
            if line.strip():
                r = json.loads(line)
                e = r["episode_id"]
                if e in seen:
                    continue
                seen.add(e)
                acc.setdefault(config_id(EGG, e), []).append(int(bool(r["success"])))
    return {c: float(np.mean(v)) for c, v in acc.items()}


def observations(policy, cond):
    """One per-configuration dict per independent run; identical runs of a deterministic policy
    collapse to one observation, or its variance is halved for free (Sect. 5.3)."""
    sets = DET_SETS if is_deterministic(policy) else OCTO_SETS
    out = [d for d in (per_config_runs(r, policy, cond) for r in sets.values()) if d]
    if is_deterministic(policy):
        uniq = []
        for r in out:
            if not any(set(r) == set(u) and all(r[k] == u[k] for k in r) for u in uniq):
                uniq.append(r)
        return uniq
    return out


def delta(a, b, cond):
    ra, rb = observations(a, cond), observations(b, cond)
    if not ra or not rb:
        return None
    cfgs = sorted(set().union(*[set(r) for r in ra]) & set().union(*[set(r) for r in rb]))
    if not cfgs:
        return None

    def stats(runs):
        mean, var, cnt = {}, {}, {}
        for k in cfgs:
            vals = [r[k] for r in runs if k in r]
            mean[k], cnt[k] = float(np.mean(vals)), len(vals)
            var[k] = float(np.var(vals, ddof=1)) if len(vals) > 1 else None
        known = [v for v in var.values() if v is not None]
        fill = float(np.mean(known)) if known else 0.0
        return mean, {k: (fill if v is None else v) for k, v in var.items()}, cnt

    ma, va, sa = stats(ra)
    mb, vb, sb = stats(rb)
    n = len(cfgs)
    d = float(np.mean([ma[k] - mb[k] for k in cfgs]))
    se = float(np.sqrt(sum(va[k] / sa[k] + vb[k] / sb[k] for k in cfgs) / n ** 2))
    return dict(delta=d, se=se, lo=d - 1.96 * se, hi=d + 1.96 * se, n=n,
                runs=(len(ra), len(rb)))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="results/controller_sweep_gpu_rep3/analysis_torque_shift_s5.md")
    args = ap.parse_args()

    L = ["# Generated: per-pair torque-limit shift at S = 5 (eggplant census)", "",
         "Generated by `scripts/analyze_torque_shift_s5.py`. Replaces the S = 3 version of the",
         "Sect. 7.3 table so that the printed shifts average to the paper's standard delta.", "",
         f"Configurations: {NC}/{NC} enumerated. Intervals carry policy noise only (Sect. 5.4).", "",
         "| pair | nominal Δ | torque ×0.5 Δ | shift | runs |",
         "|---|---|---|---:|---|"]
    shifts = []
    for o in OCTO:
        vals = {c: delta(o, OPENVLA, c) for c in CONDS}
        if not all(vals.values()):
            print(f"  SKIP {o}: missing a condition")
            continue
        nom, frc = vals["nominal"], vals["force_x0.5"]
        sh = nom["delta"] - frc["delta"]
        shifts.append(sh)
        L.append(f"| {o} vs OpenVLA | {nom['delta']:+.3f} [{nom['lo']:+.3f}, {nom['hi']:+.3f}] | "
                 f"{frc['delta']:+.3f} [{frc['lo']:+.3f}, {frc['hi']:+.3f}] | {-sh:+.3f} | "
                 f"{nom['runs'][0]}/{nom['runs'][1]} |")
    mean_shift = float(np.mean(shifts))
    L += ["", f"Mean shift over the four pairs: **{mean_shift:.3f}** "
              f"(range {min(shifts):.3f} to {max(shifts):.3f}).", ""]

    # Single-policy effect, the mechanism check of Sect. 7.4
    for p in (OPENVLA, "octo-small"):
        rates = {}
        for c in CONDS:
            runs = observations(p, c)
            cfgs = sorted(set().union(*[set(r) for r in runs]))
            rates[c] = float(np.mean([np.mean([r[k] for r in runs if k in r]) for k in cfgs]))
        L.append(f"- {p}: nominal {rates['nominal']:.3f} -> torque x0.5 "
                 f"{rates['force_x0.5']:.3f} ({rates['force_x0.5'] - rates['nominal']:+.3f})")
    L.append("")

    out = ROOT / args.out
    out.write_text("\n".join(L), encoding="utf-8")
    print("\n".join(L))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
